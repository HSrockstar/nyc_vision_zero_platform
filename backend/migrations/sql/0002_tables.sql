CREATE TABLE governance_task (
	task_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	task_code VARCHAR(40) NOT NULL, 
	request_id UUID NOT NULL, 
	request_hash VARCHAR(64) NOT NULL, 
	profile_id BIGINT NOT NULL, 
	title VARCHAR(160) NOT NULL, 
	description TEXT NOT NULL, 
	measure_type VARCHAR(40) NOT NULL, 
	priority VARCHAR(20) NOT NULL, 
	status VARCHAR(30) NOT NULL, 
	created_by BIGINT NOT NULL, 
	assignee_id BIGINT, 
	due_date DATE, 
	effective_on DATE, 
	assessment_scope JSONB DEFAULT '{}'::jsonb NOT NULL, 
	is_simulated BOOLEAN DEFAULT true NOT NULL, 
	deleted_at TIMESTAMP WITH TIME ZONE, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	version INTEGER DEFAULT 1 NOT NULL, 
	PRIMARY KEY (task_id), 
	CONSTRAINT ck_task_status CHECK (status IN ('DRAFT', 'OPEN', 'IN_PROGRESS', 'PENDING_REVIEW', 'COMPLETED', 'CANCELLED')), 
	CONSTRAINT ck_task_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')), 
	CONSTRAINT ck_task_measure CHECK (measure_type IN ('MARKING_MAINTENANCE', 'SIGNAL_REVIEW', 'PEDESTRIAN_FACILITY_REVIEW', 'FIELD_SURVEY', 'OTHER')), 
	CONSTRAINT ck_task_fields CHECK (version > 0 AND btrim(title) <> '' AND btrim(description) <> ''), 
	CONSTRAINT ck_task_simulated CHECK (is_simulated), 
	CONSTRAINT ck_task_draft_delete CHECK (deleted_at IS NULL OR status = 'DRAFT'), 
	CONSTRAINT ck_task_request_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'), 
	UNIQUE (task_code), 
	UNIQUE (request_id), 
	FOREIGN KEY(profile_id) REFERENCES risk_profile (profile_id) ON DELETE RESTRICT, 
	FOREIGN KEY(created_by) REFERENCES app_user (user_id) ON DELETE RESTRICT, 
	FOREIGN KEY(assignee_id) REFERENCES app_user (user_id) ON DELETE RESTRICT
);

CREATE INDEX ix_task_assignee_status ON governance_task (assignee_id, status, updated_at DESC) WHERE deleted_at IS NULL;

CREATE INDEX ix_task_profile ON governance_task (profile_id);

